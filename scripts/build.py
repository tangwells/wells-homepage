#!/usr/bin/env python3
"""Zero-dependency CommonJS + CSS bundler for the carrot-home Obsidian plugin."""

from __future__ import annotations

import json
import pathlib
import sys


PLUGIN_ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC_DIR = PLUGIN_ROOT / "src"
STYLES_DIR = SRC_DIR / "styles"
OUT_JS = PLUGIN_ROOT / "main.js"
OUT_CSS = PLUGIN_ROOT / "styles.css"


def build_js() -> str:
    js_files = sorted(
        (p for p in SRC_DIR.rglob("*.js")),
        key=lambda p: p.relative_to(SRC_DIR).as_posix(),
    )
    if not (SRC_DIR / "index.js").is_file():
        raise FileNotFoundError(f"Entry file not found: {SRC_DIR / 'index.js'}")

    module_entries = []
    for path in js_files:
        rel_id = "./" + path.relative_to(SRC_DIR).as_posix()
        source = path.read_text(encoding="utf-8")
        module_entries.append(
            f"  {json.dumps(rel_id)}: function (require, module, exports) {{\n{source}\n  }}"
        )

    modules_block = ",\n".join(module_entries)
    return (
        "/* AUTO-GENERATED by scripts/build.py — DO NOT EDIT DIRECTLY */\n"
        "'use strict';\n\n"
        "var __chHostRequire = typeof require === 'function' ? require : null;\n"
        "var __chModules = {\n"
        f"{modules_block}\n"
        "};\n"
        "var __chCache = Object.create(null);\n\n"
        "function __chNormalizePath(fromId, spec) {\n"
        "  var baseParts = fromId.split('/');\n"
        "  baseParts.pop();\n"
        "  var specParts = spec.split('/');\n"
        "  var out = [];\n"
        "  var i;\n"
        "  for (i = 0; i < baseParts.length; i++) {\n"
        "    if (baseParts[i] && baseParts[i] !== '.') out.push(baseParts[i]);\n"
        "  }\n"
        "  for (i = 0; i < specParts.length; i++) {\n"
        "    var seg = specParts[i];\n"
        "    if (!seg || seg === '.') continue;\n"
        "    if (seg === '..') {\n"
        "      if (out.length > 0) out.pop();\n"
        "    } else {\n"
        "      out.push(seg);\n"
        "    }\n"
        "  }\n"
        "  return './' + out.join('/');\n"
        "}\n\n"
        "function __chResolveModuleId(fromId, spec) {\n"
        "  var norm = __chNormalizePath(fromId, spec);\n"
        "  var candidates = [norm, norm + '.js', norm + '/index.js'];\n"
        "  for (var i = 0; i < candidates.length; i++) {\n"
        "    if (Object.prototype.hasOwnProperty.call(__chModules, candidates[i])) {\n"
        "      return candidates[i];\n"
        "    }\n"
        "  }\n"
        "  return null;\n"
        "}\n\n"
        "function __chRequire(fromId, spec) {\n"
        "  if (typeof spec !== 'string') {\n"
        "    throw new Error('Invalid require specifier: ' + String(spec));\n"
        "  }\n"
        "  if (spec.charAt(0) !== '.') {\n"
        "    if (!__chHostRequire) {\n"
        "      throw new Error('Host require unavailable for external module: ' + spec);\n"
        "    }\n"
        "    return __chHostRequire(spec);\n"
        "  }\n"
        "  var resolved = __chResolveModuleId(fromId, spec);\n"
        "  if (!resolved) {\n"
        "    throw new Error('Cannot find module \"' + spec + '\" from \"' + fromId + '\"');\n"
        "  }\n"
        "  if (Object.prototype.hasOwnProperty.call(__chCache, resolved)) {\n"
        "    return __chCache[resolved].exports;\n"
        "  }\n"
        "  var mod = { exports: {} };\n"
        "  __chCache[resolved] = mod;\n"
        "  var localRequire = function (childSpec) {\n"
        "    return __chRequire(resolved, childSpec);\n"
        "  };\n"
        "  try {\n"
        "    __chModules[resolved](localRequire, mod, mod.exports);\n"
        "  } catch (err) {\n"
        "    delete __chCache[resolved];\n"
        "    throw err;\n"
        "  }\n"
        "  return mod.exports;\n"
        "}\n\n"
        "module.exports = __chRequire('./index.js', './index.js');\n"
    )


def build_css() -> str:
    css_files = sorted(
        (p for p in STYLES_DIR.glob("*.css")),
        key=lambda p: p.name,
    )
    parts = ["/* AUTO-GENERATED by scripts/build.py — DO NOT EDIT DIRECTLY */"]
    for path in css_files:
        content = path.read_text(encoding="utf-8").strip()
        if content:
            parts.append(f"/* ---- {path.name} ---- */\n{content}")
    return "\n\n".join(parts) + "\n"


def main() -> int:
    check_only = "--check" in sys.argv[1:]
    expected_js = build_js()
    expected_css = build_css()

    if check_only:
        actual_js = OUT_JS.read_text(encoding="utf-8") if OUT_JS.is_file() else None
        actual_css = OUT_CSS.read_text(encoding="utf-8") if OUT_CSS.is_file() else None
        ok = True
        if actual_js != expected_js:
            print(f"OUT OF SYNC: {OUT_JS} does not match src/**/*.js (run scripts/build.py)", file=sys.stderr)
            ok = False
        if actual_css != expected_css:
            print(f"OUT OF SYNC: {OUT_CSS} does not match src/styles/*.css (run scripts/build.py)", file=sys.stderr)
            ok = False
        if not ok:
            return 1
        print("OK: main.js and styles.css match src/")
        return 0

    OUT_JS.write_text(expected_js, encoding="utf-8")
    OUT_CSS.write_text(expected_css, encoding="utf-8")
    print(f"Built {OUT_JS.name} ({len(expected_js)} bytes) and {OUT_CSS.name} ({len(expected_css)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
